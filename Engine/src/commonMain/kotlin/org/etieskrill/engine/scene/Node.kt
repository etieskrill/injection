package org.etieskrill.engine.scene

import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.launch
import net.bifreus.kml.Vec2
import net.bifreus.kml.Vec4
import org.etieskrill.engine.input.KeyEvent
import org.etieskrill.engine.input.Key

abstract class Node<T : Node<T>> {

    var position = Vec2(0f)
        set(value) {
            field(value)
        }
    val absolutePosition: Vec2
        get() {
            if (parent == null) return Vec2(position)
            return parent!!.absolutePosition + position
        }

    var size = Vec2(-1f)
        set(value) {
            field(value)
            invalidate()
        }

    var formattedSize = Vec2(size) //TODO protecc or internal
        set(value) {
            field(value)
        }

    var scaleMode = ScaleMode.CONTENT
        set(value) {
            field = value
            invalidate()
        }

    enum class ScaleMode {
        CONTENT, FIXED, GROW
    }

    var computedFixedSize = false //TODO protecc or internal

    var alignment = Alignment.TOP_LEFT
        set(value) {
            field = value
            invalidate()
        }
    var margin = Vec4(0) //Swizzle: top, bottom, left, right
        set(value) {
            field(value)
        }

    var isVisible = true

    var colour = Vec4(0)
        set(value) {
            field(value)
            renderedColour(value)
        }
    val renderedColour = Vec4(0)

    var parent: Node<*>? = null
        set(value) {
            check(value != this) { "A node may not be it's own parent" }
            checkRecursively({ it != this }) { "A node may not be it's own parent anywhere in the hierarchy" }

            field = value
            if (field != null) invalidate()
        }

    var focused: Boolean = false
        internal set
    var focusRequestCallback: ((Node<*>) -> Boolean)? = null

    protected val uiDispatcher get() = rootUiDispatcher!!
    internal var rootUiDispatcher: CoroutineDispatcher? = null
        get() = parent
            ?.rootUiDispatcher
            ?: field
            ?: error("Root node has no coroutine dispatcher set; probably due to it not being in valid scene")

    protected val uiScope get() = rootUiScope!!
    internal var rootUiScope: CoroutineScope? = null
        get() = parent
            ?.rootUiScope
            ?: field
            ?: error("Root node has no coroutine scope set; probably due to it not being in valid scene")

    protected fun ui(block: suspend CoroutineScope.() -> Unit) = uiScope.launch(block = block)

    protected var shouldFormat = true

    enum class Alignment {
        FIXED_POSITION,

        TOP_LEFT, TOP, TOP_RIGHT,
        CENTER_LEFT, CENTER, CENTER_RIGHT,
        BOTTOM_LEFT, BOTTOM, BOTTOM_RIGHT
    }

    open fun update(delta: Double) = Unit

    /**
     * Computes the [Node]'s [formattedSize] based on its children (if any) given its [scaleMode] and sets the
     * [computedFixedSize] flag.
     *
     * Must be called prior to [layout].
     *
     * Works bottom-to-top.
     *
     * @see layout
     */
    open fun computeFixedSizes() {
        if (!shouldFormat) return

        when (scaleMode) {
            ScaleMode.FIXED, ScaleMode.CONTENT -> {
                computedFixedSize = true
                formattedSize(size)
            }

            ScaleMode.GROW -> computedFixedSize = false
        }
    }

    /**
     * Partitions the [Node]'s area to assign a size to children (if any) with [ScaleMode.GROW], then positions the
     * children according to their layout preference.
     *
     * Requires [computeFixedSizes] to be called beforehand.
     *
     * Works top-to-bottom.
     *
     * @see computeFixedSizes
     */
    open fun layout() = Unit

    open fun render(batch: Batch) = Unit

    fun show() {
        isVisible = true
    }

    fun hide() {
        isVisible = false
    }

    private fun checkRecursively(condition: (Node<*>) -> Boolean, message: () -> String) {
        var parent = this as Node<*>
        while (parent.parent != null) {
            parent = parent.parent!!
            if (!condition(parent)) error(message())
        }
    }

    protected fun shouldFormat() =
        if (shouldFormat) {
            shouldFormat = false
            true
        } else {
            false
        }

    fun invalidate() {
        this.shouldFormat = true
        parent?.invalidate()
    }

    /**
     * Handle an event generated by a mouse click.
     *
     * This event is generated only for the root node. Every node may decide for itself whether this event hits the
     * node, is intercepted, and/or passed on to potential children.
     */
    open fun handleHit(event: KeyEvent, posX: Double, posY: Double): Boolean {
        requestFocus()
        return false
    }

    open fun doesHit(posX: Double, posY: Double): Boolean {
        val absPos = absolutePosition
        return absPos.x + formattedSize.x >= posX && posX >= absPos.x &&
                absPos.y + formattedSize.y >= posY && posY >= absPos.y
    }

    /**
     * Handle an event generated by dragging (holding a button and moving) the mouse.
     *
     * > Currently, only the [primary mouse button][Key.LEFT_MOUSE] will generate this event.
     *
     * This event is generated only for the root node. Every node may decide for itself whether this event hits the
     * node, is intercepted, and/or passed on to potential children.
     */
    //primary mouse key is just implied for now TODO detect any mouse key (do keyboard keys make sense?)
    open fun handleDrag(deltaX: Double, deltaY: Double, posX: Double, posY: Double) = false

    open fun handleHover(posX: Double, posY: Double) = false

    /**
     * Handle an event generated by a key press of any physical key, as mapped by [Key] (GLFW).
     *
     * This event is generated only for the root node. Every node may decide for itself whether this event hits the
     * node, is intercepted, or passed on to potential children.
     */
    open fun handleKey(event: KeyEvent) = false

    /**
     * Handle a character as generated by the OS's text input system. Usable e.g. for text input. The characters
     * generated take into account the locale, modifiers, and dead keys, and are encoded in UTF-16.
     *
     * This event is generated only for the currently focused node, or the root node by default. Every node may decide
     * for itself whether this event hits the node, is intercepted, or passed on to potential children.
     *
     * @see requestFocus
     */
    open fun handleCharacter(char: Char) = false

    private fun internalRequestFocus(node: Node<*>): Boolean =
        focusRequestCallback?.invoke(node)
            ?: parent?.internalRequestFocus(node)
            ?: false

    /**
     * Calling this method will request [this Node][Node] to be focused. This means, that all non-cursor input
     * will be directed to this node instead of the hierarchy root.
     * <p>
     * By default, the root node will be in focus.
     *
     * @return whether the request was successful
     */
    fun requestFocus(): Boolean = internalRequestFocus(this)

}
